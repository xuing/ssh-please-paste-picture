#!/bin/bash
# Integration tests of the macOS client on a real Mac: the real pasteboard, the real
# Terminal.app window and the watcher in wrapper mode, with a stand-in for ssh. Run
# it on a Mac with a GUI session that nobody is using (CI: the macOS jobs). It
# replaces the pasteboard and opens Terminal and Calculator windows.
#
#   bash tests/mac/jxa.sh
#
# The stand-in ssh (written below) answers -V and -G, plays the interactive session
# (it sleeps until killed), and plays the server for an upload: it stores the bytes
# under $work/server and answers "<size> /tmp/ssh-paste-<hash>.<ext>" after a delay,
# or fails, as $work/mode says ("ok SECONDS" or "fail SECONDS").
set -u
# shellcheck source-path=SCRIPTDIR
. "$(dirname "$0")/lib.sh"

tmp=${TMPDIR:-/tmp}
work=$(cd "$(mktemp -d "${tmp%/}/ssh-paste-jxa.XXXXXXXX")" && pwd -P)
usertmp=$(getconf DARWIN_USER_TEMP_DIR)
rm -f "${usertmp%/}/ssh-paste-debug.log"
mkdir -p "$work/server"
trap 'pkill -f "$work/fakessh" 2> /dev/null; rm -rf "$work"' EXIT

cat > "$work/fakessh" << EOF
#!/bin/sh
work='$work'
EOF
cat >> "$work/fakessh" << 'EOF'
case "$1" in
    -V) echo 'OpenSSH_9.9p2, LibreSSL 3.3.6' >&2; exit 0 ;;
    -G) printf 'hostname 127.0.0.1\nport 22\nrequesttty auto\nsessiontype default\nstdinnull no\nremotecommand none\n'; exit 0 ;;
esac
for last in "$@"; do :; done
case "$last" in
    *"sh -c '"*)
        # ... ssh-paste HASH SIZE EXT KEEP 'DIR'
        hash=$(printf '%s\n' "$last" | awk '{ print $(NF-4) }')
        ext=$(printf '%s\n' "$last" | awk '{ print $(NF-2) }')
        printf '%s\n' "$last" | awk '{ print $NF }' > "$work/dirword"
        read -r mode delay < "$work/mode"
        cat > "$work/server/ssh-paste-$hash.$ext"
        echo "$hash.$ext" >> "$work/uploads"
        sleep "$delay"
        if [ "$mode" = fail ]; then echo 'Permission denied (publickey).' >&2; exit 255; fi
        echo "$(wc -c < "$work/server/ssh-paste-$hash.$ext" | tr -d ' ') /tmp/ssh-paste-$hash.$ext"
        exit 0 ;;
esac
echo $$ > "$work/session.pid"
exec sleep 3600
EOF
chmod +x "$work/fakessh"

# Test images: a screenshot of this screen, a JPEG made from it, a TIFF.
screencapture -x "$work/shot.png"
sips -s format jpeg "$work/shot.png" --out "$work/shot.jpg" > /dev/null
sips -s format tiff "$work/shot.png" --out "$work/shot.tiff" > /dev/null
cp "$work/shot.png" "$work/second.png"
printf 'x' >> "$work/second.png"   # another hash, still a PNG for the pasteboard tools

# The watcher logs to $TMPDIR/ssh-paste-debug.log through NSTemporaryDirectory(),
# which is the per-user temporary folder when it does not follow TMPDIR.
debuglog() { for d in "$work" "${usertmp%/}"; do if [ -f "$d/ssh-paste-debug.log" ]; then echo "$d/ssh-paste-debug.log"; return; fi; done; echo /dev/null; }
uploads() { if [ -f "$work/uploads" ]; then wc -l < "$work/uploads" | tr -d ' '; else echo 0; fi; }
# shellcheck disable=SC2317,SC2329 # called through wait_for
more_uploads() { [ "$(uploads)" -gt "$1" ]; }
# shellcheck disable=SC2317,SC2329 # called through wait_for
logged() { grep -q "$1" "$(debuglog)" 2> /dev/null; }

section 'a stale change count: the write is refused and the pasteboard stays'
pb text 'copied by the user'
check "$(pb stale-write)" refused 'publish() refuses a basis that is not the current change count'
check "$(pbpaste)" 'copied by the user' 'the text the user copied is still there'

section 'the watcher starts in a Terminal window (wrapper mode)'
echo 'ok 3' > "$work/mode"
terminal_run session "export SSH_PASTE_SSH='$work/fakessh' SSH_PASTE_DEBUG=1 TMPDIR='$work/'
exec '$repo/src/ssh-paste-mac' --dir /tmp/ testhost"
if wait_for 30 test -f "$work/session.pid"; then pass 'the session runs'; else fail 'the session did not start'; fi
if wait_for 30 logged 'watching com.apple.Terminal'; then
    pass "the watcher found Terminal.app: $(grep 'watching' "$(debuglog)" | head -n 1 | sed 's/^.*watching //')"
else
    fail 'the watcher did not report Terminal.app'; cat "$(debuglog)"
fi

section 'a paste during the upload waits for it and gets the remote path'
pb png "$work/shot.png"
want=/tmp/ssh-paste-$(sha16 "$work/shot.png").png
wait_for 20 entry_is "$want" || fail 'no promise was written'
paste_timed "$work/p1"
check "$(cat "$work/p1")" "$want" 'pbpaste got the remote path'
check "$(cat "$work/dirword")" "'/tmp'" 'wrapper mode sends --dir /tmp/ as /tmp, the folder the reply is checked against'
waited=$(cat "$work/p1.ms")
if [ "$waited" -ge 1000 ]; then pass "pbpaste waited for the upload ($waited ms)"; else fail "pbpaste did not wait for the 3 s upload ($waited ms)"; fi
if cmp -s "$work/shot.png" "$work/server/$(basename "$want")"; then pass 'the server got the exact bytes'; else fail 'the uploaded bytes differ'; fi
d=$(pb dump)
case $d in *'"org.nspasteboard.TransientType"'*'"org.nspasteboard.AutoGeneratedType"'*) pass 'the entry is marked transient and auto-generated' ;; *) fail "history markers missing: $d" ;; esac
case $d in *'"public.png"'*) pass 'the image stays on the pasteboard' ;; *) fail "no image: $d" ;; esac
paste_timed "$work/p2"
check "$(cat "$work/p2")" "$want" 'a second paste gets the same path'

section 'a failed upload gives an empty paste and takes the path back'
echo 'fail 2' > "$work/mode"
before=$(uploads)
pb png "$work/second.png"
wait_for 20 more_uploads "$before" || fail 'no upload started'
paste_timed "$work/p3"
check "$(cat "$work/p3")" '' 'pbpaste got nothing'
if wait_for 10 sh -c "osascript -l JavaScript '$pbjs' dump | grep -q '\"text\":\"\"'"; then pass 'the path came off the pasteboard'; else fail "the path stayed: $(pb dump)"; fi

section 'the owner window: a paste in another app gets nothing at once'
echo 'ok 6' > "$work/mode"
cp "$work/shot.png" "$work/third.png"
printf 'yz' >> "$work/third.png"
before=$(uploads)
pb png "$work/third.png"
wait_for 20 more_uploads "$before" || fail 'no upload started'
activate Calculator com.apple.calculator
paste_timed "$work/p4"
check "$(cat "$work/p4")" '' 'pbpaste in front of Calculator got nothing'
waited=$(cat "$work/p4.ms")
if [ "$waited" -lt 2500 ]; then pass "and did not wait for the upload ($waited ms)"; else fail "it waited $waited ms"; fi
sleep 7
if wait_for 10 sh -c "osascript -l JavaScript '$pbjs' dump | grep -q '\"owner\":0'"; then pass 'with Calculator in front the plain image is back'; else fail "no plain image: $(pb dump)"; fi
activate Terminal com.apple.Terminal
want=/tmp/ssh-paste-$(sha16 "$work/third.png").png
wait_for 10 sh -c "osascript -l JavaScript '$pbjs' dump | grep -q '\"text\":\"$want\"'" || fail 'the watcher did not write the path again'
paste_timed "$work/p5"
check "$(cat "$work/p5")" "$want" 'back in Terminal, pbpaste gets the path'
check "$(grep -c "$(sha16 "$work/third.png")" "$work/uploads")" 1 'uploaded once'

section 'a paste that waits gets nothing when another app comes to the front meanwhile'
echo 'ok 6' > "$work/mode"
cp "$work/shot.png" "$work/fourth.png"
printf 'w' >> "$work/fourth.png"
before=$(uploads)
pb png "$work/fourth.png"
wait_for 20 more_uploads "$before" || fail 'no upload started'
paste_timed "$work/p8" &
paster=$!
sleep 1
activate Calculator com.apple.calculator
wait "$paster"
check "$(cat "$work/p8")" '' 'the paste started in Terminal got nothing: Calculator was in front when the upload ended'
waited=$(cat "$work/p8.ms")
if [ "$waited" -ge 2500 ]; then pass "it waited for the upload first ($waited ms)"; else fail "it did not wait for the upload ($waited ms)"; fi
activate Terminal com.apple.Terminal
want=/tmp/ssh-paste-$(sha16 "$work/fourth.png").png
wait_for 10 entry_is "$want" || fail "the watcher did not write the path again: $(pb dump)"
paste_timed "$work/p9"
check "$(cat "$work/p9")" "$want" 'back in Terminal, pbpaste gets the path'
check "$(grep -c "$(sha16 "$work/fourth.png")" "$work/uploads")" 1 'uploaded once'

section 'a TIFF-only image is uploaded as PNG'
activate Terminal com.apple.Terminal
pb tiff "$work/shot.tiff"
wait_for 20 entry_like '/tmp/ssh-paste-*.png' || fail "no entry for the TIFF: $(pb dump)"
paste_timed "$work/p7"
case $(cat "$work/p7") in
    /tmp/ssh-paste-*.png)
        f=$work/server/$(basename "$(cat "$work/p7")")
        if [ "$(head -c 8 "$f" | od -An -tx1 | tr -d ' \n')" = 89504e470d0a1a0a ]; then pass 'pbpaste got a .png path and the server got PNG bytes'; else fail 'the server did not get a PNG'; fi ;;
    *) fail "unexpected paste: $(cat "$work/p7")" ;;
esac

section 'image files copied in Finder'
echo 'ok 1' > "$work/mode"
# Copied while another app is in front, so the copy can be read before the watcher acts.
activate Calculator com.apple.calculator
pb finder "$work/shot.png" "$work/shot.jpg"
echo "        what the copy put on the pasteboard: $(pb items)"
# Another process sometimes sees only the first of the two file URLs that this writer
# puts there (on macOS 15 most runs, on macOS 26 some). The watcher must offer every
# file the pasteboard holds, so the test follows what it holds.
pb file-paths > "$work/held"
held=$(wc -l < "$work/held" | tr -d ' ')
if [ "$held" -lt 2 ]; then echo "        note: another process reads $held of the 2 copied files on this macOS"; fi
if [ "$held" -lt 1 ]; then fail 'no copied file on the pasteboard'; fi
want=
while IFS= read -r f; do want="$want /tmp/ssh-paste-$(sha16 "$f").${f##*.}"; done < "$work/held"
want=${want# }
files_json=$(awk 'BEGIN { printf "[" } { printf "%s\"%s\"", (NR > 1 ? "," : ""), $0 } END { printf "]" }' "$work/held")
activate Terminal com.apple.Terminal
wait_for 20 entry_is "$want" || fail "no entry with every path: $(pb dump)"
paste_timed "$work/p6"
check "$(cat "$work/p6")" "$want" "pbpaste gets the remote path of each of the $held file(s)"
d=$(pb dump)
case $d in *'public.file-url'*) fail "a file URL is on the pasteboard while the path is offered: $d" ;; *) pass 'no file URL while the path is offered' ;; esac
case $d in *'"public.png"'*) pass 'the first image is offered as PNG' ;; *) fail "no PNG: $d" ;; esac
activate Calculator com.apple.calculator
if wait_for 10 files_are "$files_json"; then
    pass 'with Calculator in front the file URLs are back'
else
    fail "the files are not back: $(pb dump)"
fi
activate Terminal com.apple.Terminal

# The copied files move away while the path is on the pasteboard. On exit the
# watcher reads the pasteboard again and cannot read the files any more; it must
# still take the path back, using the image its entry carries.
wait_for 20 entry_is "$want" || fail "no entry with every path before the files move: $(pb dump)"
while IFS= read -r f; do mv "$f" "$f.moved"; done < "$work/held"

section 'the session ends after the copied files moved: the path comes off and the watcher stops'
kill "$(cat "$work/session.pid")"
if wait_for 20 sh -c "! pgrep -f 'ssh-paste.js --watch-wrapper' > /dev/null"; then pass 'the watcher stopped'; else fail 'the watcher still runs'; fi
d=$(pb dump)
case $d in *'"owner":0'*'"text":""'*) pass 'the plain image is back' ;; *) fail "not restored: $d" ;; esac
check "$(pbpaste)" '' 'pbpaste gets no path any more'
check "$(find "$work" "${usertmp%/}" -maxdepth 1 -name 'ssh-paste.[0-9]*' | wc -l | tr -d ' ')" 0 'the private folders of the watcher are gone'
section 'the debug log'
cat "$(debuglog)"

finish
